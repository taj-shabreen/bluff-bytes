import { randomInt, randomUUID } from 'node:crypto';

export const TERMS = [
  { term: 'Hallucination', category: 'ARTIFICIAL INTELLIGENCE', definition: 'A confident but incorrect answer generated by an AI model.' },
  { term: 'Backpropagation', category: 'MACHINE LEARNING', definition: 'A method that adjusts a neural network by sending its errors backward through the layers.' },
  { term: 'Cache', category: 'COMPUTER SCIENCE', definition: 'A small, fast storage area that keeps frequently used data close at hand.' },
  { term: 'Overfitting', category: 'MACHINE LEARNING', definition: 'When a model memorizes its training examples and struggles with new ones.' },
  { term: 'Handshake', category: 'NETWORKING', definition: 'A brief exchange that lets two devices agree how to communicate.' },
] as const;

export type Term = (typeof TERMS)[number];
export type Player = { id: string; token: string; name: string; score: number; lastSeen: number };
export type Answer = { id: string; playerId: string | null; text: string; correct: boolean };
export type Vote = { playerId: string; answerId: string };
export type Round = { term: Term; answers: Answer[]; votes: Vote[]; correctAnswerId: string | null };
export type Room = {
  code: string;
  hostId: string;
  players: Player[];
  status: 'lobby' | 'playing' | 'finished';
  phase: 'lobby' | 'writing' | 'voting' | 'reveal' | 'finished';
  roundIndex: number;
  rounds: Round[];
  message: string;
  version: number;
};

export class GameError extends Error {
  constructor(public status: number, message: string) { super(message); }
}

function fail(message: string, status = 400): never { throw new GameError(status, message); }

export function createRoom(code: string, name: string, token: string, id: string, now = Date.now()): Room {
  return {
    code,
    hostId: id,
    players: [{ id, token, name, score: 0, lastSeen: now }],
    status: 'lobby',
    phase: 'lobby',
    roundIndex: 0,
    rounds: [],
    message: '',
    version: 1,
  };
}

export function publicState(room: Room, token: string, now = Date.now()) {
  const me = room.players.find(player => player.token === token);
  if (!me) return null;
  const players = room.players.map(player => ({
    id: player.id,
    name: player.name,
    score: player.score,
    connected: now - player.lastSeen < 35_000,
    host: player.id === room.hostId,
  }));
  const common = {
    code: room.code,
    status: room.status,
    players,
    me: { id: me.id, name: me.name, score: me.score, host: me.id === room.hostId },
    roundNumber: room.roundIndex + 1,
    totalRounds: TERMS.length,
    phase: room.phase,
    scores: room.players.map(player => ({ id: player.id, name: player.name, score: player.score })),
    message: room.message,
    version: room.version,
  };
  if (room.status === 'lobby') return { ...common, submissionCount: 0 };
  if (room.status === 'finished') return { ...common, winner: [...room.players].sort((a, b) => b.score - a.score)[0]?.id };

  const round = room.rounds[room.roundIndex];
  if (!round) throw new Error('The active round is missing.');
  const roundData = { ...common, term: round.term.term, category: round.term.category, submissionCount: round.answers.length };
  if (room.phase === 'writing') {
    return { ...roundData, definition: null, answers: [], submitted: round.answers.some(answer => answer.playerId === me.id), voteCount: 0, voted: false };
  }
  if (room.phase === 'voting') {
    return {
      ...roundData,
      definition: null,
      answers: round.answers.map(answer => ({ id: answer.id, text: answer.text, own: answer.playerId === me.id })),
      submitted: true,
      voteCount: round.votes.length,
      voted: round.votes.some(vote => vote.playerId === me.id),
    };
  }
  return {
    ...roundData,
    phase: 'reveal' as const,
    definition: round.term.definition,
    answers: round.answers.map(answer => ({
      id: answer.id,
      text: answer.text,
      own: answer.playerId === me.id,
      correct: answer.correct,
      votes: round.votes.filter(vote => vote.answerId === answer.id).length,
      voters: round.votes.filter(vote => vote.answerId === answer.id).map(vote => room.players.find(player => player.id === vote.playerId)?.name).filter(Boolean),
    })),
    voteCount: round.votes.length,
    correctAnswerId: round.correctAnswerId,
  };
}

export function applyAction(room: Room, token: string, body: Record<string, unknown>, now = Date.now(), id = randomUUID()) {
  const player = room.players.find(candidate => candidate.token === token);
  if (!player) fail('Your seat has expired. Rejoin with the room code.', 401);

  if (body.action === 'state') return publicState(room, token, now);
  if (body.action === 'heartbeat') {
    player.lastSeen = now;
    return publicState(room, token, now);
  }
  if (body.action === 'start') {
    if (player.id !== room.hostId) fail('Only the host can start the game.');
    if (room.status !== 'lobby') fail('A game is already in progress.');
    if (room.players.length < 2) fail('At least 2 players are needed to start.');
    room.status = 'playing';
    room.phase = 'writing';
    room.roundIndex = 0;
    room.players.forEach(candidate => { candidate.score = 0; });
    room.rounds = TERMS.map(term => ({ term, answers: [], votes: [], correctAnswerId: null }));
    room.message = '';
  } else if (body.action === 'submit') {
    if (room.status !== 'playing' || room.phase !== 'writing') fail('Submissions are closed.');
    const round = room.rounds[room.roundIndex];
    if (round.answers.some(answer => answer.playerId === player.id)) fail('You have already submitted this round.');
    const text = typeof body.text === 'string' ? body.text.trim() : '';
    if (text.length < 8 || text.length > 240) fail('Write a definition between 8 and 240 characters.');
    round.answers.push({ id, playerId: player.id, text, correct: false });
    if (round.answers.length === room.players.length) {
      const correct = { id: randomUUID(), playerId: null, text: round.term.definition, correct: true };
      round.answers.splice(randomInt(round.answers.length + 1), 0, correct);
      round.correctAnswerId = correct.id;
      room.phase = 'voting';
    }
  } else if (body.action === 'vote') {
    if (room.status !== 'playing' || room.phase !== 'voting') fail('Voting is not open.');
    const round = room.rounds[room.roundIndex];
    if (round.votes.some(vote => vote.playerId === player.id)) fail('You have already voted this round.');
    const answer = round.answers.find(candidate => candidate.id === body.answerId);
    if (!answer) fail('That answer is not on the list.');
    if (answer.playerId === player.id) fail('You cannot vote for your own definition.');
    round.votes.push({ playerId: player.id, answerId: answer.id });
    if (round.votes.length === room.players.length) {
      for (const vote of round.votes) {
        const voter = room.players.find(candidate => candidate.id === vote.playerId);
        const chosen = round.answers.find(candidate => candidate.id === vote.answerId);
        if (!voter || !chosen) throw new Error('The completed vote is invalid.');
        if (chosen.correct) voter.score += 2;
        else {
          const author = room.players.find(candidate => candidate.id === chosen.playerId);
          if (author) author.score += 1;
        }
      }
      room.phase = 'reveal';
    }
  } else if (body.action === 'next') {
    if (room.status !== 'playing' || room.phase !== 'reveal') fail('The round has not finished.');
    if (room.roundIndex === TERMS.length - 1) {
      room.status = 'finished';
      room.phase = 'finished';
    } else {
      room.roundIndex++;
      room.phase = 'writing';
    }
  } else if (body.action === 'restart') {
    if (player.id !== room.hostId) fail('Only the host can start a new game.');
    room.status = 'lobby';
    room.phase = 'lobby';
    room.roundIndex = 0;
    room.rounds = [];
    room.players.forEach(candidate => { candidate.score = 0; });
    room.message = 'New game ready!';
  } else {
    fail('Unknown game action.');
  }
  player.lastSeen = now;
  return publicState(room, token, now);
}

